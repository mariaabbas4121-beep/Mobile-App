-- NeighborShare chat (Phase 2C)
--
-- One private conversation per ACCEPTED borrow request, between its borrower
-- and its lender. Nobody else can see it, and there is no way to start a
-- conversation with an arbitrary user.
--
--   * A conversation is created when a request is accepted (trigger), and on
--     demand by open_conversation() for a participant of an accepted request.
--     Both are idempotent: borrow_request_id is unique.
--   * Its participants are copied from the request by the database; they are
--     never chosen by a client. Request details cannot change after creation
--     (see borrow_requests_before_update), so the copy cannot drift.
--   * Pending, declined and cancelled requests have no conversation, and
--     messages can only be added while the request is accepted.
--   * Archiving the listing keeps the conversation and messaging open: an
--     accepted reservation survives archiving, and the two people still need
--     to arrange the handover.
--
-- Messages are text only (1..2000 characters, not blank). Each carries a
-- client-generated id; (conversation, sender, client id) is unique, so a
-- retried send stores the message once.
--
-- Errors raised by this migration use these SQLSTATEs (mapped by the API):
--   NSC01 chat not available: the request is not accepted
--   NSC02 conversation not found (or the caller is not a participant)
--   NSC03 client id already used for a different message
--   42501 caller may not send (not a participant, or account not in good standing)
--   23514 message empty, blank or too long

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table public.conversations (
  id                    uuid primary key default gen_random_uuid(),
  borrow_request_id     uuid not null unique references public.borrow_requests (id) on delete cascade,
  -- Copied from the request; never supplied by a client.
  listing_id            uuid not null,
  borrower_id           uuid not null,
  lender_id             uuid not null,
  borrower_last_read_at timestamptz,
  lender_last_read_at   timestamptz,
  last_message_at       timestamptz,
  created_at            timestamptz not null default now(),
  constraint conversations_two_people check (borrower_id <> lender_id)
);

comment on table public.conversations is
  'Private chat between the borrower and lender of one accepted borrow request.';

create index conversations_borrower_idx on public.conversations (borrower_id);
create index conversations_lender_idx on public.conversations (lender_id);

create table public.messages (
  id              uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations (id) on delete cascade,
  sender_id       uuid not null references public.profiles (id) on delete cascade,
  -- Generated by the sending device; makes retries idempotent.
  client_id       uuid not null,
  body            text not null,
  created_at      timestamptz not null default now(),
  constraint messages_body_length check (char_length(body) between 1 and 2000),
  constraint messages_body_not_blank check (body ~ '[^[:space:]]'),
  constraint messages_client_id_unique unique (conversation_id, sender_id, client_id)
);

comment on table public.messages is 'Text messages in a conversation. Immutable once sent.';

-- History is read newest first, page by page.
create index messages_conversation_idx on public.messages (conversation_id, created_at desc, id desc);

-- ---------------------------------------------------------------------------
-- Functions
-- ---------------------------------------------------------------------------

-- Creates the conversation of an accepted request if it does not exist yet.
-- Internal: called by the trigger below and by open_conversation().
create function public.ensure_conversation(p_borrow_request_id uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  cid uuid;
begin
  insert into public.conversations (borrow_request_id, listing_id, borrower_id, lender_id)
  select r.id, r.listing_id, r.borrower_id, r.lender_id
    from public.borrow_requests r
   where r.id = p_borrow_request_id and r.status = 'accepted'
  on conflict (borrow_request_id) do nothing;
  select c.id into cid from public.conversations c where c.borrow_request_id = p_borrow_request_id;
  return cid;
end;
$$;

-- Accepting a request opens its conversation in the same transaction.
create function public.borrow_requests_open_conversation()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.ensure_conversation(new.id);
  return null;
end;
$$;

-- The conversation of a request the caller takes part in. Null when there is
-- no such request for the caller (so ids reveal nothing); NSC01 when the
-- request exists but is not accepted.
create function public.open_conversation(p_borrow_request_id uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  req_status public.borrow_request_status;
begin
  if me is null then
    return null;
  end if;
  select r.status into req_status
    from public.borrow_requests r
   where r.id = p_borrow_request_id and (r.borrower_id = me or r.lender_id = me);
  if not found then
    return null;
  end if;
  if req_status <> 'accepted' then
    raise exception 'chat_not_available' using errcode = 'NSC01';
  end if;
  return public.ensure_conversation(p_borrow_request_id);
end;
$$;

-- Conversations the caller takes part in, most recent activity first, with
-- the listing, the request dates, the other participant's display name, the
-- latest message (first 200 characters) and the caller's unread count.
-- SECURITY DEFINER to read the other participant's profile; the participant
-- filter below is the access rule.
create function public.list_conversations(
  p_id     uuid default null,
  p_limit  integer default 20,
  p_offset integer default 0
)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  with me as (select auth.uid() as id),
  matches as (
    select c.*,
           case when c.borrower_id = me.id then 'borrower' else 'lender' end as viewer_role,
           case when c.borrower_id = me.id then c.borrower_last_read_at else c.lender_last_read_at end as my_read_at,
           case when c.borrower_id = me.id then c.lender_id else c.borrower_id end as other_id,
           me.id as me_id
      from public.conversations c, me
     where me.id is not null
       and (c.borrower_id = me.id or c.lender_id = me.id)
       and (p_id is null or c.id = p_id)
  ),
  page as (
    select m.*, pg_catalog.row_number() over (order by coalesce(m.last_message_at, m.created_at) desc, m.id) as ord
      from matches m
     order by ord
     limit least(greatest(p_limit, 1), 50)
    offset greatest(p_offset, 0)
  )
  select pg_catalog.jsonb_build_object(
    'total', (select pg_catalog.count(*) from matches),
    'items', coalesce((
      select pg_catalog.jsonb_agg(
        pg_catalog.jsonb_build_object(
          'id', p.id,
          'borrow_request_id', p.borrow_request_id,
          'viewer_role', p.viewer_role,
          'created_at', p.created_at,
          'last_message_at', p.last_message_at,
          'request', pg_catalog.jsonb_build_object(
            'id', r.id, 'status', r.status, 'start_date', r.start_date, 'end_date', r.end_date
          ),
          'listing', pg_catalog.jsonb_build_object(
            'id', l.id,
            'title', l.title,
            'archived', l.archived_at is not null,
            'cover_path', (select i.storage_path from public.listing_images i
                            where i.listing_id = l.id order by i.created_at limit 1)
          ),
          'other', pg_catalog.jsonb_build_object('id', p.other_id, 'display_name', o.display_name),
          'last_message', (
            select pg_catalog.jsonb_build_object(
                     'id', x.id, 'sender_id', x.sender_id, 'body', pg_catalog.left(x.body, 200), 'created_at', x.created_at)
              from public.messages x
             where x.conversation_id = p.id
             order by x.created_at desc, x.id desc
             limit 1
          ),
          'unread_count', (
            select pg_catalog.count(*)
              from public.messages x
             where x.conversation_id = p.id
               and x.sender_id <> p.me_id
               and (p.my_read_at is null or x.created_at > p.my_read_at)
          )
        ) order by p.ord)
        from page p
        join public.borrow_requests r on r.id = p.borrow_request_id
        join public.listings l on l.id = p.listing_id
        left join public.profiles o on o.id = p.other_id
    ), '[]'::jsonb)
  );
$$;

-- One page of history, newest first, strictly older than the cursor
-- (created_at, id) when one is given. SECURITY INVOKER: Row-Level Security
-- decides which rows the caller sees, so a non-participant gets nothing.
create function public.list_messages(
  p_conversation_id   uuid,
  p_before_created_at timestamptz default null,
  p_before_id         uuid default null,
  p_limit             integer default 30
)
returns setof public.messages
language sql
stable
security invoker
set search_path = ''
as $$
  select m.*
    from public.messages m
   where m.conversation_id = p_conversation_id
     and (p_before_created_at is null
          or (m.created_at, m.id) < (p_before_created_at, coalesce(p_before_id, 'ffffffff-ffff-ffff-ffff-ffffffffffff'::uuid)))
   order by m.created_at desc, m.id desc
   limit least(greatest(p_limit, 1), 100);
$$;

-- Stores a message from the caller, once per client id. Returns the stored
-- message, whether this call created it, and both participants (so the
-- server can tell them about it). SECURITY INVOKER: the insert policy below
-- is what allows it.
create function public.send_message(p_conversation_id uuid, p_client_id uuid, p_body text)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  c record;
  m public.messages;
  created boolean := true;
begin
  select cv.id, cv.borrower_id, cv.lender_id, cv.borrow_request_id into c
    from public.conversations cv
   where cv.id = p_conversation_id;
  if not found or me is null then
    raise exception 'conversation_not_found' using errcode = 'NSC02';
  end if;
  if not exists (select 1 from public.borrow_requests r where r.id = c.borrow_request_id and r.status = 'accepted') then
    raise exception 'chat_not_available' using errcode = 'NSC01';
  end if;

  insert into public.messages (conversation_id, sender_id, client_id, body)
  values (p_conversation_id, me, p_client_id, p_body)
  on conflict (conversation_id, sender_id, client_id) do nothing
  returning * into m;

  if not found then
    created := false;
    select * into m from public.messages x
     where x.conversation_id = p_conversation_id and x.sender_id = me and x.client_id = p_client_id;
    if m.body is distinct from p_body then
      raise exception 'client_id_reused' using errcode = 'NSC03';
    end if;
  end if;

  return pg_catalog.jsonb_build_object(
    'created', created,
    'borrower_id', c.borrower_id,
    'lender_id', c.lender_id,
    'message', pg_catalog.to_jsonb(m)
  );
end;
$$;

-- New messages move the conversation up the list, and count as read by the
-- sender.
create function public.messages_after_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.conversations c
     set last_message_at = greatest(coalesce(c.last_message_at, new.created_at), new.created_at),
         borrower_last_read_at = case when c.borrower_id = new.sender_id
                                      then greatest(coalesce(c.borrower_last_read_at, new.created_at), new.created_at)
                                      else c.borrower_last_read_at end,
         lender_last_read_at = case when c.lender_id = new.sender_id
                                    then greatest(coalesce(c.lender_last_read_at, new.created_at), new.created_at)
                                    else c.lender_last_read_at end
   where c.id = new.conversation_id;
  return null;
end;
$$;

-- Marks everything in the conversation as read by the caller. False when the
-- caller is not a participant.
create function public.mark_conversation_read(p_conversation_id uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
begin
  if me is null then
    return false;
  end if;
  update public.conversations c
     set borrower_last_read_at = case when c.borrower_id = me then pg_catalog.now() else c.borrower_last_read_at end,
         lender_last_read_at = case when c.lender_id = me then pg_catalog.now() else c.lender_last_read_at end
   where c.id = p_conversation_id and (c.borrower_id = me or c.lender_id = me);
  return found;
end;
$$;

-- ---------------------------------------------------------------------------
-- Triggers
-- ---------------------------------------------------------------------------

create trigger borrow_requests_open_conversation
  after update of status on public.borrow_requests
  for each row when (new.status = 'accepted' and old.status <> 'accepted')
  execute function public.borrow_requests_open_conversation();

create trigger messages_after_insert
  after insert on public.messages
  for each row execute function public.messages_after_insert();

-- Requests accepted before this migration get their conversation now.
insert into public.conversations (borrow_request_id, listing_id, borrower_id, lender_id)
select r.id, r.listing_id, r.borrower_id, r.lender_id
  from public.borrow_requests r
 where r.status = 'accepted'
on conflict (borrow_request_id) do nothing;

-- ---------------------------------------------------------------------------
-- Privileges
-- ---------------------------------------------------------------------------

revoke all on table public.conversations, public.messages from public, anon, authenticated, service_role;

-- Conversations are created and updated only by the functions above.
grant select on table public.conversations to authenticated;
-- Messages are immutable: no update or delete for users. The id and the
-- timestamp are always set by the database.
grant select on table public.messages to authenticated;
grant insert (conversation_id, sender_id, client_id, body) on table public.messages to authenticated;
grant select, insert, update, delete on table public.conversations, public.messages to service_role;

revoke execute on function
  public.ensure_conversation(uuid),
  public.borrow_requests_open_conversation(),
  public.open_conversation(uuid),
  public.list_conversations(uuid, integer, integer),
  public.list_messages(uuid, timestamptz, uuid, integer),
  public.send_message(uuid, uuid, text),
  public.messages_after_insert(),
  public.mark_conversation_read(uuid)
  from public, anon, authenticated;

grant execute on function
  public.open_conversation(uuid),
  public.list_conversations(uuid, integer, integer),
  public.list_messages(uuid, timestamptz, uuid, integer),
  public.send_message(uuid, uuid, text),
  public.mark_conversation_read(uuid)
  to authenticated;

-- ---------------------------------------------------------------------------
-- Row-Level Security
-- ---------------------------------------------------------------------------

alter table public.conversations enable row level security;
alter table public.messages enable row level security;

create policy "conversations: participants can read"
  on public.conversations for select
  to authenticated
  using (borrower_id = (select auth.uid()) or lender_id = (select auth.uid()));

create policy "messages: participants can read"
  on public.messages for select
  to authenticated
  using (exists (
    select 1 from public.conversations c
     where c.id = conversation_id
       and (c.borrower_id = (select auth.uid()) or c.lender_id = (select auth.uid()))
  ));

-- Only as yourself, only in your own conversation, only while its request is
-- accepted, and only while your account is in good standing.
create policy "messages: participants in good standing can send"
  on public.messages for insert
  to authenticated
  with check (
    sender_id = (select auth.uid())
    and exists (
      select 1
        from public.conversations c
        join public.borrow_requests r on r.id = c.borrow_request_id
       where c.id = conversation_id
         and (c.borrower_id = (select auth.uid()) or c.lender_id = (select auth.uid()))
         and r.status = 'accepted'
    )
    and exists (
      select 1 from public.profiles p
       where p.id = (select auth.uid()) and p.account_status in ('active', 'restricted')
    )
  );
